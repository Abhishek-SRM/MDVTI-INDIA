document.addEventListener('DOMContentLoaded', () => {
    // Helper function to check if element is in viewport
    const observeElement = (selector, callback, options = { threshold: 0.2 }) => {
        const elements = document.querySelectorAll(selector);
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    callback(entry.target);
                    observer.unobserve(entry.target);
                }
            });
        }, options);
        elements.forEach(el => observer.observe(el));
    };

    // 1. Hero Section Animations
    const heroTimeline = anime.timeline({
        easing: 'easeOutExpo',
        duration: 1000
    });

    heroTimeline
    .add({
        targets: '.hero-title',
        translateY: [50, 0],
        opacity: [0, 1],
        delay: anime.stagger(200),
        duration: 1200
    })
    .add({
        targets: '.fluid-subtitle',
        translateY: [30, 0],
        opacity: [0, 1],
        duration: 1000,
        offset: '-=800'
    })
    .add({
        targets: '.body-lead',
        translateY: [20, 0],
        opacity: [0, 1],
        duration: 1000,
        offset: '-=800'
    })
    .add({
        targets: '.hero-section .bg-white a', // CTA Buttons
        translateY: [20, 0],
        opacity: [0, 1],
        delay: anime.stagger(100),
        offset: '-=800'
    })
    .add({
        targets: '.hero-section .grid > div', // Feature Grid
        translateY: [20, 0],
        opacity: [0, 1],
        delay: anime.stagger(100),
        offset: '-=800'
    });

    // 2. "Who Is This Course For?" Cards Stagger
    observeElement('.who-section .grid > div', (target) => {
        // We want to animate the parent grid's children when the grid comes into view
        // But observeElement is called for each child. 
        // To avoid multiple triggers for the same group, we can check if it's already animating
        // Or just animate the specific target.
        
        anime({
            targets: target,
            translateY: [50, 0],
            opacity: [0, 1],
            duration: 800,
            easing: 'easeOutCubic',
            delay: 100 // Small delay for individual feel
        });
    });

    // 3. "The Big Promise" Table Rows
    // We can target the rows directly
    const promiseRows = document.querySelectorAll('.bg-white table tbody tr');
    if(promiseRows.length > 0) {
        const observer = new IntersectionObserver((entries) => {
            if(entries[0].isIntersecting) {
                anime({
                    targets: '.bg-white table tbody tr',
                    translateX: [-20, 0],
                    opacity: [0, 1],
                    delay: anime.stagger(100),
                    duration: 800,
                    easing: 'easeOutQuad'
                });
                observer.disconnect();
            }
        }, { threshold: 0.2 });
        
        const table = document.querySelector('.bg-white table');
        if(table) observer.observe(table);
    }

    // 4. Bento Grid Curriculum (Generated by JS, so we need to wait or use mutation observer)
    // Since it's generated by renderCurriculumCards(), we can try to hook into it or just wait a bit.
    // The render function adds 'opacity-0' class. We can animate that.
    
    // Let's assume the render function runs and we can observe the grid container
    const bentoGrid = document.getElementById('bentoGrid');
    if (bentoGrid) {
        const bentoObserver = new MutationObserver((mutations) => {
            mutations.forEach((mutation) => {
                if (mutation.addedNodes.length) {
                    // Animate newly added nodes
                    anime({
                        targets: '#bentoGrid > div',
                        translateY: [50, 0],
                        opacity: [0, 1],
                        delay: anime.stagger(150),
                        duration: 800,
                        easing: 'easeOutQuart'
                    });
                    bentoObserver.disconnect(); // Run once
                }
            });
        });
        bentoObserver.observe(bentoGrid, { childList: true });
    }

    // 5. Meet Your Instructors
    observeElement('.grid.md\\:grid-cols-3 > div', (target) => {
         // This selector might be too generic, let's be more specific if possible
         // The instructors section has a specific structure
    });
    
    // Better selector for instructors
    const instructorSection = document.querySelector('section.py-24.bg-white');
    if (instructorSection) {
        const instructors = instructorSection.querySelectorAll('.grid > div');
        const observer = new IntersectionObserver((entries) => {
            if (entries[0].isIntersecting) {
                anime({
                    targets: instructors,
                    translateY: [60, 0],
                    opacity: [0, 1],
                    delay: anime.stagger(200),
                    duration: 1000,
                    easing: 'easeOutElastic(1, .8)'
                });
                observer.disconnect();
            }
        }, { threshold: 0.1 });
        observer.observe(instructorSection);
    }

    // 6. Floating CTA Pulse/Float
    anime({
        targets: '.fixed.bottom-6.right-6',
        translateY: [-5, 5],
        duration: 2000,
        loop: true,
        direction: 'alternate',
        easing: 'easeInOutSine'
    });

    // 7. Micro Interactions on Hover (using event delegation)
    document.body.addEventListener('mouseover', (e) => {
        if (e.target.closest('.micro-banner')) {
            anime({
                targets: e.target.closest('.micro-banner'),
                scale: 1.05,
                duration: 300,
                easing: 'easeOutQuad'
            });
        }
    });
    
    document.body.addEventListener('mouseout', (e) => {
        if (e.target.closest('.micro-banner')) {
            anime({
                targets: e.target.closest('.micro-banner'),
                scale: 1,
                duration: 300,
                easing: 'easeOutQuad'
            });
        }
    });

    // 8. FAQ Animation
    const faqContainer = document.getElementById('faqContainer');
    if (faqContainer) {
        const faqObserver = new MutationObserver((mutations) => {
            mutations.forEach((mutation) => {
                if (mutation.addedNodes.length) {
                    anime({
                        targets: '.accordion-item',
                        translateY: [20, 0],
                        opacity: [0, 1],
                        delay: anime.stagger(100),
                        duration: 600,
                        easing: 'easeOutQuad'
                    });
                    faqObserver.disconnect();
                }
            });
        });
        faqObserver.observe(faqContainer, { childList: true, subtree: true });
    }

});
